    @Test
    fun migrateSixToEightAddsCanonicalAudioFeatureStorage() {
        helper.createDatabase(TEST_DATABASE_6_8, 6).close()
        helper.runMigrationsAndValidate(
            TEST_DATABASE_6_8,
