            true,
            MIGRATION_6_7,
            MIGRATION_7_8,
        ).close()
    }

    @Test
    fun migrateSevenToEightRepairsDerivedFeatureTableAndPreservesTracks() {
        val database = helper.createDatabase(TEST_DATABASE_7_8_REPAIR, 6)
        database.execSQL(
            "INSERT INTO `tracks` (`id`, `title`, `normalizedTitle`, `artist`, `normalizedArtist`, `album`, " +
                "`durationMs`, `trackNumber`, `year`, `artworkRef`, `favorite`, `hidden`, `createdAtEpochMs`, `updatedAtEpochMs`) " +
                "VALUES ('repair-track', 'Repair Track', 'repair track', NULL, NULL, NULL, 1000, NULL, NULL, NULL, 0, 0, 1, 1)",
        )
        MIGRATION_6_7.migrate(database)
        database.execSQL("DROP TABLE `audio_feature_vectors`")
        database.execSQL(
            "CREATE TABLE `audio_feature_vectors` (`id` TEXT NOT NULL, `legacyPayload` TEXT, PRIMARY KEY(`id`))",
        )
        database.version = 7
        database.close()

        val migrated = helper.runMigrationsAndValidate(
            TEST_DATABASE_7_8_REPAIR,
            8,
            true,
            MIGRATION_7_8,
        )
        migrated.query("SELECT `id` FROM `tracks` WHERE `id` = 'repair-track'").use { cursor ->
            assertTrue(cursor.moveToFirst())
        }
        migrated.close()
    }

    @Test
    fun migrateTenToElevenAddsTelegramSendQueue() {
        // Schema 11 was generated by the historical CI build but was never committed to source.
        // Exercise the migration directly from the committed schema-10 fixture instead of silently
        // skipping this regression test because MigrationTestHelper cannot load a missing 11.json.
        val database = helper.createDatabase(TEST_DATABASE_10_11, 10)
        MIGRATION_10_11.migrate(database)
        database.version = 11

        database.query("SELECT name FROM sqlite_master WHERE type = 'table' AND name = 'telegram_send_jobs'").use { cursor ->
            assertTrue(cursor.moveToFirst())
        }
        listOf(
            "index_telegram_send_jobs_trackId",
            "index_telegram_send_jobs_state",
            "index_telegram_send_jobs_activeDedupeKey",
        ).forEach { indexName ->
            database.query(
                "SELECT name FROM sqlite_master WHERE type = 'index' AND name = ?",
                arrayOf(indexName),
            ).use { cursor -> assertTrue(cursor.moveToFirst()) }
        }
        database.close()
    }

    @Test
    fun migrateElevenToTwelveBackfillsUnicodeFtsAndCandidateIndexes() {
        // Reconstruct a real version-11 database from the committed v10 schema + the production
        // 10->11 migration. This keeps 11->12 coverage valid without fabricating schema history.
        val database = helper.createDatabase(TEST_DATABASE_11_12, 10)
        MIGRATION_10_11.migrate(database)
        database.version = 11
        database.execSQL(
            "INSERT INTO `tracks` (`id`, `title`, `normalizedTitle`, `artist`, `normalizedArtist`, `album`, " +
                "`durationMs`, `trackNumber`, `year`, `artworkRef`, `favorite`, `hidden`, `createdAtEpochMs`, `updatedAtEpochMs`) " +
                "VALUES ('english-track', 'Radiohead Song', 'radiohead song', 'Radiohead', 'radiohead', 'Album', 180000, NULL, NULL, NULL, 0, 0, 1, 1)",
        )
        database.execSQL(
            "INSERT INTO `tracks` (`id`, `title`, `normalizedTitle`, `artist`, `normalizedArtist`, `album`, " +
                "`durationMs`, `trackNumber`, `year`, `artworkRef`, `favorite`, `hidden`, `createdAtEpochMs`, `updatedAtEpochMs`) " +
                "VALUES ('persian-track', 'موسیقی شب', 'موسیقی شب', 'هنرمند', 'هنرمند', 'آلبوم', 200000, NULL, NULL, NULL, 0, 0, 1, 1)",
        )
        database.close()

        val migrated = helper.runMigrationsAndValidate(
            TEST_DATABASE_11_12,
            12,
            true,
            MIGRATION_11_12,
        )

        migrated.query(
            "SELECT name FROM sqlite_master WHERE type = 'index' " +
                "AND name = 'index_tracks_normalizedTitle_normalizedArtist_durationMs'",
        ).use { cursor -> assertTrue(cursor.moveToFirst()) }
        migrated.query(
            "SELECT name FROM sqlite_master WHERE type = 'index' " +
                "AND name = 'index_track_sources_contentHashSha256'",
        ).use { cursor -> assertTrue(cursor.moveToFirst()) }
        migrated.query(
            "SELECT trackId FROM track_search_fts WHERE track_search_fts MATCH ?",
            arrayOf("\"radio*\""),
        ).use { cursor ->
            assertTrue(cursor.moveToFirst())
            assertEquals("english-track", cursor.getString(0))
        }
        migrated.query(
            "SELECT trackId FROM track_search_fts WHERE track_search_fts MATCH ?",
            arrayOf("\"موسی*\""),
        ).use { cursor ->
            assertTrue(cursor.moveToFirst())
            assertEquals("persian-track", cursor.getString(0))
        }
        migrated.close()
    }

